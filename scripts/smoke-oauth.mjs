import assert from 'node:assert/strict'
import { randomBytes, createHash } from 'node:crypto'
const resource = new URL(process.env.MCP_PUBLIC_URL || 'http://127.0.0.1:3000/mcp')
const origin = resource.origin
const callback = (process.env.MCP_OAUTH_REDIRECT_URIS || '').split(',')[0]
assert(callback, 'Configure an explicit callback URI')
const metadata = await fetch(origin+'/.well-known/oauth-authorization-server')
assert.equal(metadata.status,200)
const config=await metadata.json()
assert.equal(config.issuer,origin)
assert(config.code_challenge_methods_supported.includes('S256'))
const protectedMetadata=await fetch(origin+'/.well-known/oauth-protected-resource/mcp')
assert.equal(protectedMetadata.status,200)
assert.equal((await protectedMetadata.json()).resource,resource.href)
assert.equal((await fetch(resource)).status,401)
const badRegistration=await fetch(config.registration_endpoint,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({redirect_uris:['https://untrusted.invalid/callback']})})
assert.equal(badRegistration.status,400)
const registration=await fetch(config.registration_endpoint,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({client_name:'Deployment smoke test',redirect_uris:[callback],token_endpoint_auth_method:'none'})})
assert.equal(registration.status,201)
const {client_id}=await registration.json()
const verifier=randomBytes(32).toString('base64url')
const state=randomBytes(16).toString('hex')
const q=new URLSearchParams({client_id,redirect_uri:callback,resource:resource.href,response_type:'code',scope:'mcp:read',code_challenge_method:'S256',code_challenge:createHash('sha256').update(verifier).digest('base64url'),state})
const page=await fetch(config.authorization_endpoint+'?'+q,{redirect:'manual'})
assert.equal(page.status,200)
const html=await page.text()
const ticket=html.match(/name="ticket" value="([^"]+)"/)?.[1]
assert(ticket)
const setCookie=page.headers.get('set-cookie')
assert.match(setCookie,/HttpOnly/)
if(resource.protocol==='https:') assert.match(setCookie,/Secure/)
const missingCsrf=await fetch(origin+'/oauth/consent',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({ticket,decision:'deny'}),redirect:'manual'})
assert.equal(missingCsrf.status,400)
const denied=await fetch(origin+'/oauth/consent',{method:'POST',headers:{Origin:origin,Cookie:setCookie.split(';')[0],'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({ticket,decision:'deny'}),redirect:'manual'})
assert.equal(denied.status,303)
const target=new URL(denied.headers.get('location'))
assert.equal(target.searchParams.get('error'),'access_denied')
assert.equal(target.searchParams.get('state'),state)
assert.equal(target.searchParams.get('iss'),origin)
console.log('PASS: live OAuth discovery, callback restrictions, registration, login form, secure cookie, CSRF and denied consent. No owner password used and no access token issued.')
